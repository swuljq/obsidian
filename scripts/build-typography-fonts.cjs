const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const target = path.join(root, "snippets", "typography.css");
const startMarker = "/* BEGIN LOCAL FONT DATA */";
const endMarker = "/* END LOCAL FONT DATA */";
const css = fs.readFileSync(target, "utf8");
const start = css.indexOf(startMarker);
const end = css.indexOf(endMarker);
if (start < 0 || end < start || css.indexOf(startMarker, start + 1) >= 0) {
    throw new Error("Expected one generated-font block in typography.css");
}

const fonts = [
    { file: "HarmonyOS_Sans_SC_Regular.woff", family: "HarmonyOS Sans SC", weight: 400, mime: "font/woff", format: "woff" },
    { file: "HarmonyOS_Sans_SC_Bold.woff", family: "HarmonyOS Sans SC", weight: 700, mime: "font/woff", format: "woff" },
    { file: "Cascadia-Code-Regular.ttf", family: "Cascadia Code Local", weight: 400, mime: "font/ttf", format: "truetype" },
];
const faces = fonts.map(font => {
    const data = fs.readFileSync(path.join(root, "snippets", "font.css", "fonts", font.file)).toString("base64");
    return `@font-face {\n    font-family: "${font.family}";\n    src: url("data:${font.mime};base64,${data}") format("${font.format}");\n    font-style: normal;\n    font-weight: ${font.weight};\n    font-display: swap;\n}`;
});
const block = [startMarker, "/* Generated by node scripts/build-typography-fonts.cjs; do not edit this block. */", ...faces, endMarker].join("\n");
const result = css.slice(0, start) + block + css.slice(end + endMarker.length);
if (result !== css) fs.writeFileSync(target, result, "utf8");
console.log(`Embedded ${fonts.length} local font faces in typography.css (${Buffer.byteLength(result)} bytes).`);
